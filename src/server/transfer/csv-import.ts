// CSV import, streamed. The upload is parsed as it arrives (never buffered
// whole), counted against the size limit byte by byte, and inserted in
// batches with one statement per batch:
//
//   INSERT INTO t (a, b) SELECT a::type, b::type FROM unnest($1::text[], $2::text[])
//
// so PostgreSQL parses every value with its own input functions. Each batch
// runs under a savepoint. In "skip invalid rows" mode a failing batch is
// retried row by row to isolate the bad rows; in "all or nothing" mode the
// first failure (with its row number) rolls back the whole import.
// Row contents are never logged.

export const importOptionsSchema = z.object({
    schema: z.string().min(1).max(200),
    table: z.string().min(1).max(200),
    hasHeader: z.boolean().default(true),
    delimiter: z.enum([',', ';', '\t', '|']).default(','),
    /** For each target column, the CSV column index that feeds it. */
    mapping: z
        .array(
            z.object({
                column: z.string().min(1).max(200),
                source: z.number().int().min(0).max(1000),
            }),
        )
        .min(1, 'Map at least one column.')
        .max(400),
    /** CSV values that mean NULL. The empty string by default. */
    nullValues: z.array(z.string().max(20)).max(5).default(['']),
    mode: z.enum(['atomic', 'skip_invalid']).default('atomic'),
})

export type ImportOptions = z.infer<typeof importOptionsSchema>

export interface ImportReport {
    totalRows: number
    inserted: number
    failed: { row: number; message: string }[]
    failedCount: number
    committed: boolean
    durationMs: number
}

const BATCH_SIZE = 500
const MAX_REPORTED_FAILURES = 200

function sizeLimiter(limit: number) {
    let seen = 0
    return new Transform({
        transform(chunk: Buffer, _encoding, callback) {
            seen += chunk.length
            if (seen > limit) {
                callback(
                    new AppError(
                        'payload_too_large',
                        `The file is larger than ${Math.round(limit / 1024 / 1024)} MB.`,
                    ),
                )
                return
            }
            callback(null, chunk)
        },
    })
}

class NothingImported extends Error {}

class RowFailure extends Error {
    constructor(
        readonly row: number,
        message: string,
    ) {
        super(message)
    }
}

export async function importCsv(
    userId: string,
    projectId: string,
    body: ReadableStream<Uint8Array>,
    options: ImportOptions,
): Promise<ImportReport> {
    const target = await projectTarget(userId, projectId, 'write')
    await assertWithinQuota(target)
    const live = await liveSchema(target, { fresh: true })
    const table = live.tables.find(
        (candidate) => candidate.schema === options.schema && candidate.name === options.table,
    )
    if (!table) throw notFound('Table')

    const columns = options.mapping.map((entry) => {
        const column = table.columns.find((candidate) => candidate.name === entry.column)
        if (!column) throw new AppError('bad_request', `Unknown column "${entry.column}".`)
        if (column.generated || column.identity === 'always') {
            throw new AppError(
                'bad_request',
                `${column.name} is generated by the database and cannot be imported.`,
            )
        }
        return { ...entry, type: column.type }
    })
    if (new Set(columns.map((column) => column.column)).size !== columns.length) {
        throw new AppError('bad_request', 'Each column can only be mapped once.')
    }

    const insertSql = batchInsert(table, columns)
    const nulls = new Set(options.nullValues)
    const started = performance.now()
    const report: ImportReport = {
        totalRows: 0,
        inserted: 0,
        failed: [],
        failedCount: 0,
        committed: false,
        durationMs: 0,
    }

    const fail = (row: number, message: string) => {
        report.failedCount += 1
        if (report.failed.length < MAX_REPORTED_FAILURES) report.failed.push({ row, message })
    }

    const parser = Readable.fromWeb(body as Parameters<typeof Readable.fromWeb>[0])
        .pipe(sizeLimiter(config().IMPORT_MAX_BYTES))
        .pipe(
            parse({
                delimiter: options.delimiter,
                bom: true,
                relax_column_count: true,
                skip_empty_lines: true,
                from_line: options.hasHeader ? 2 : 1,
            }),
        )

    async function insertBatch(ctx: TxContext, rows: { line: number; values: string[] }[]) {
        const params = columns.map((column) =>
            rows.map((row) => {
                const value = row.values[column.source]
                return value === undefined || nulls.has(value) ? null : value
            }),
        )
        await ctx.client.query('SAVEPOINT batch')
        try {
            await ctx.client.query(insertSql, params)
            await ctx.client.query('RELEASE SAVEPOINT batch')
            report.inserted += rows.length
            return
        } catch (error) {
            await ctx.client.query('ROLLBACK TO SAVEPOINT batch')
            if (rows.length === 1) {
                throw new RowFailure(rows[0]!.line, (error as Error).message)
            }
        }
        // Isolate the failing rows one at a time.
        for (const row of rows) {
            try {
                await insertBatch(ctx, [row])
            } catch (error) {
                if (!(error instanceof RowFailure)) throw error
                if (options.mode === 'atomic') throw error
                fail(error.row, error.message)
            }
        }
    }

    try {
        await withTargetTransaction(
            target,
            userId,
            'write',
            async (ctx) => {
                let batch: { line: number; values: string[] }[] = []
                let line = options.hasHeader ? 1 : 0
                for await (const record of parser as AsyncIterable<string[]>) {
                    line += 1
                    report.totalRows += 1
                    batch.push({ line, values: record })
                    if (batch.length >= BATCH_SIZE) {
                        await insertBatch(ctx, batch)
                        batch = []
                    }
                }
                if (batch.length > 0) await insertBatch(ctx, batch)
                // Nothing to commit: roll back rather than record an empty import.
                if (report.inserted === 0) throw new NothingImported()
            },
            { timeoutMs: 120_000 },
        )
        report.committed = true
    } catch (error) {
        if (error instanceof RowFailure) {
            fail(error.row, error.message)
            report.inserted = 0
        } else if (error instanceof NothingImported) {
            report.inserted = 0
        } else if (error instanceof AppError) {
            throw error
        } else if ((error as { code?: string }).code?.startsWith('CSV_')) {
            throw new AppError(
                'bad_request',
                `The file is not valid CSV: ${(error as Error).message}`,
            )
        } else {
            throw new AppError('database_error', (error as Error).message)
        }
    } finally {
        parser.destroy()
    }

    report.durationMs = Math.round(performance.now() - started)
    invalidateSchema(target.connection.id)
    await recordQuery({
        projectId,
        userId,
        sql: insertSql,
        mode: 'write',
        status: report.committed ? 'success' : 'error',
        statementCount: 1,
        rowCount: report.inserted,
        durationMs: report.durationMs,
        errorMessage: report.committed ? null : (report.failed[0]?.message ?? null),
        source: 'import',
    })
    if (report.committed) {
        await recordActivity({
            userId,
            projectId,
            kind: 'data.imported',
            message: `Imported ${report.inserted} row${report.inserted === 1 ? '' : 's'} into ${table.name}${report.failedCount ? ` (${report.failedCount} skipped)` : ''}`,
        })
    }
    return report
}

function batchInsert(table: SchemaTable, columns: { column: string; type: string }[]): string {
    const names = columns.map((column) => quoteIdent(column.column))
    const arrays = columns.map((_, index) => `$${index + 1}::text[]`)
    const aliases = columns.map((_, index) => `c${index}`)
    const casts = columns.map((column, index) => `${aliases[index]}::${column.type}`)
    return (
        `INSERT INTO ${qualify(table.schema, table.name)} (${names.join(', ')}) ` +
        `SELECT ${casts.join(', ')} FROM unnest(${arrays.join(', ')}) AS u(${aliases.join(', ')})`
    )
}
